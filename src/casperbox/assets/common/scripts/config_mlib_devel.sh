#!/usr/bin/env bash
# Configure mlib_devel (runs as the container user):
#   1. Clone mlib_devel and device-tree-xlnx into ~/toolflow
#   2. Install mlib_devel's python dependencies into the conda env
#   3. Generate ~/.startsg.local and load it from ~/.bashrc
#   4. Link mlib_devel/startsg to ~/.local/bin/startsg
set -euo pipefail

: "${MLIB_DEVEL_REPO:?}" "${MLIB_DEVEL_BRANCH:?}"
: "${DEVICE_TREE_XLNX_REPO:?}" "${DEVICE_TREE_XLNX_BRANCH:?}"
: "${CONDA_ENV_NAME:?}" "${VIVADO_VERSION:?}"
CONDA_DIR="${CONDA_DIR:-/opt/conda}"
GIT_CLONE_DEPTH="${GIT_CLONE_DEPTH:-1}"

toolflow_dir="${HOME}/toolflow"
mlib_dir="${toolflow_dir}/mlib_devel"
dt_dir="${toolflow_dir}/device-tree-xlnx"
startsg_local="${HOME}/.startsg.local"
user_bin="${HOME}/.local/bin"

depth_args=()
if [[ "${GIT_CLONE_DEPTH}" != "0" ]]; then
    depth_args=(--depth "${GIT_CLONE_DEPTH}")
fi

mkdir -p "${toolflow_dir}"

echo ">>> Cloning mlib_devel (${MLIB_DEVEL_BRANCH})"
git clone "${depth_args[@]}" --single-branch --branch "${MLIB_DEVEL_BRANCH}" \
    "${MLIB_DEVEL_REPO}" "${mlib_dir}"

echo ">>> Cloning device-tree-xlnx (${DEVICE_TREE_XLNX_BRANCH})"
git clone "${depth_args[@]}" --single-branch --branch "${DEVICE_TREE_XLNX_BRANCH}" \
    "${DEVICE_TREE_XLNX_REPO}" "${dt_dir}"

echo ">>> Installing mlib_devel dependencies into conda env ${CONDA_ENV_NAME}"
# shellcheck disable=SC1091
source "${CONDA_DIR}/etc/profile.d/conda.sh"
conda activate "${CONDA_ENV_NAME}"
python -m pip install --no-cache-dir --upgrade pip
# requirements.txt has -e git+... dependencies; put their sources in ~/toolflow/src
(cd "${mlib_dir}" && python -m pip install --no-cache-dir --src "${toolflow_dir}/src" -r requirements.txt)

echo ">>> Generating ${startsg_local}"
cat > "${startsg_local}" <<EOF
# Generated by casperbox at image build time
# Vivado is mounted at the host path; the entrypoint writes /etc/casper/runtime.env at container startup
[ -r /etc/casper/runtime.env ] && . /etc/casper/runtime.env
export XILINX_PATH COMPOSER_PATH
export PLATFORM=lin64
export JASPER_BACKEND=vivado
export XLNX_DT_REPO_PATH=${dt_dir}
# No MATLAB in the container: startsg requires MATLAB_PATH to be a readable directory, so point it at /tmp
export MATLAB_PATH=/tmp
export FRONTEND=scilab
export CASPER_DEBUG=off
# python: shells activate conda env ${CONDA_ENV_NAME} automatically via /etc/profile.d/casper.sh
EOF

echo ">>> Loading ~/.startsg.local from ~/.bashrc"
if ! grep -qsF 'source ~/.startsg.local' "${HOME}/.bashrc"; then
    cat >> "${HOME}/.bashrc" <<'EOF'

# mlib_devel local config (XILINX_PATH / JASPER_BACKEND / XLNX_DT_REPO_PATH etc.)
[ -r ~/.startsg.local ] && source ~/.startsg.local
EOF
fi

echo ">>> Linking ${user_bin}/startsg -> ${mlib_dir}/startsg"
mkdir -p "${user_bin}"
ln -sfn "${mlib_dir}/startsg" "${user_bin}/startsg"

echo "mlib_devel configured: ${mlib_dir}"
